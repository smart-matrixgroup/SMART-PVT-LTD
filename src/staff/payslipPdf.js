// Payslip as a real .pdf file — shared by the admin Salary page and the
// staff portal so both download exactly the same document.
import { monthLabel } from './staffUtils.js';
import { formatLKR, toInt } from '../erp/money.js';
import { saveSlipPdf } from '../erp/utils/reportPdf.js';

const amount = v => formatLKR(v).replace(/^\s*LKR[\s.]*/i, '').replace(/[,]/g, ',');

export function savePayslipPdf(p) {
  if (!p) return null;
  const gross = toInt(p.basicSalary) + toInt(p.allowances);
  return saveSlipPdf({
    docTitle: 'PAYSLIP',
    docNo: p.payslipNo || '',
    heading: [`Payslip — ${monthLabel(p.month)}`],
    blocks: [
      {
        title: 'Employee', columns: 2, items: [
          { label: 'Name', value: p.staffName || '—' },
          { label: 'Payment date', value: p.paidOn || '—' },
          { label: 'Designation', value: p.staffRole || '—' },
          { label: 'Staff ID', value: p.staffId || '—' },
        ],
      },
      {
        title: 'Payment', columns: 2, items: [
          { label: 'Method', value: p.method || '—' },
          { label: 'Reference', value: p.reference || '—' },
        ],
      },
    ],
    table: {
      columns: [
        { label: 'PARTICULARS', width: 46 },
        { label: 'EARNINGS (LKR)', width: 27, align: 'right' },
        { label: 'DEDUCTIONS (LKR)', width: 27, align: 'right' },
      ],
      rows: [
        ['Basic salary', amount(p.basicSalary), ''],
        ['Allowances', amount(p.allowances), ''],
        ['Total deductions', '', amount(p.deductions)],
        ['Gross salary', amount(gross), ''],
      ],
      total: { label: 'NET PAY', value: formatLKR(p.net) },
    },
    note: 'Generated by the SMART ERP payslip register.',
    fileName: `PAYSLIP-${String(p.payslipNo || p.staffName || 'STAFF').replace(/[^\w]+/g, '-')}-${p.month || ''}.pdf`,
  });
}
